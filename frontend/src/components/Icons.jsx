// Category Icon Helper Function
export function getCategoryIcon(catId, size = 16) {
  switch (catId) {
    case 'mobiles':
      return <MobileIcon size={size} />;
    case 'electronics':
      return <ElectronicsIcon size={size} />;
    case 'fashion':
      return <FashionIcon size={size} />;
    case 'home':
      return <HomeIcon size={size} />;
    case 'appliances':
      return <AppliancesIcon size={size} />;
    case 'beauty':
      return <BeautyIcon size={size} />;
    default:
      return <SparklesIcon size={size} />;
  }
}

